SELECT FLAVOR
FROM (
    SELECT FLAVOR, SUM(TOTAL_ORDER) AS T_O
    FROM (
        SELECT SHIPMENT_ID, FLAVOR, TOTAL_ORDER
        FROM FIRST_HALF
        UNION
        SELECT SHIPMENT_ID, FLAVOR, TOTAL_ORDER
        FROM JULY 
    )
    GROUP BY FLAVOR
    ORDER BY T_O DESC)
WHERE ROWNUM <= 3;